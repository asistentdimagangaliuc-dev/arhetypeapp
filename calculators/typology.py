def reinin_traits(tim: str) -> dict[str, str]:
    """11 неюнговских признаков Рейнина для ТИМа (ключ — EN-название пары)."""
    k = resolve_tim(tim)
    let = TIMS[k]["letters"]
    differs = {"E": let[0] != "E", "N": let[1] != "N", "T": let[2] != "T", "P": let[3] != "p"}
    out = {}
    for d in REININ:
        odd = sum(differs[c] for c in d["set"]) % 2 == 1
        ru, en = d["other"] if odd else d["ile"]
        key = f"{d['ile'][1]}/{d['other'][1]}"
        out[key] = f"{ru} ({en})"
    return out


