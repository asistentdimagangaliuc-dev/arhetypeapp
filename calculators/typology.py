LIKERT_SCALE = {0: "совсем не про меня", 1: "скорее не про меня", 2: "отчасти", 3: "скорее про меня", 4: "точно про меня"}
FC_SCALE = {"A": "точно A", "a": "скорее A", "?": "не могу выбрать", "b": "скорее B", "B": "точно B"}
_ENNEA_ROUND_ORDER = [3, 7, 1, 5, 9, 2, 6, 4, 8]


def get_questionnaire(part: str = "all", include_extra: bool = False) -> dict[str, Any]:
    """Опросник в порядке предъявления. part: 'socionics' | 'enneagram' | 'all'.

    Уточняющие пункты (X1/X2, FU-…) по умолчанию не включаются: агент задаёт их,
    только если о них просит поле `followup` в результате подсчёта.
    """
    out: dict[str, Any] = {"instructions": [
        "Отвечайте, как вы ведёте себя обычно и давно (с юности), а не как хотели бы или как требует работа.",
        "Нет хороших и плохих ответов: оба утверждения в паре нормальны.",
        "Вынужденный выбор: A / a (скорее A) / ? (не могу выбрать) / b (скорее B) / B.",
        "Шкала утверждений: 0 — совсем не про меня … 4 — точно про меня.",
    ]}
    if part in ("socionics", "all"):
        base = [i for i in SOCIONICS_ITEMS.values() if include_extra or not i.extra]
        order = sorted(base, key=lambda i: (i.extra, i.id.split("-")[2], list(SOC_POLES).index(i.scale)))
        out["socionics"] = [{"id": i.id, "A": i.text_a, "B": i.text_b, "answer_format": FC_SCALE} for i in order]
    if part in ("enneagram", "all"):
        en = []
        for r in range(1, 5):
            for t in _ENNEA_ROUND_ORDER:
                it = ENNEAGRAM_ITEMS[f"EN-{t}-{r}"]
                en.append({"id": it.id, "text": it.text, "answer_format": LIKERT_SCALE})
        out["enneagram"] = en
        inst = []
        for r in range(1, 5):
            for k in ("sp", "so", "sx"):
                it = INSTINCT_ITEMS[f"IN-{k.upper()}-{r}"]
                inst.append({"id": it.id, "text": it.text, "answer_format": LIKERT_SCALE})
        inst += [{"id": i.id, "A": i.text_a, "B": i.text_b, "answer_format": FC_SCALE} for i in INSTINCT_FC_ITEMS.values()]
        out["instincts"] = inst
        if include_extra:
            out["enneagram_followup"] = [{"id": i.id, "A": i.text_a, "B": i.text_b, "answer_format": FC_SCALE}
                                         for i in ENNEAGRAM_FOLLOWUP_ITEMS.values()]
    return out


