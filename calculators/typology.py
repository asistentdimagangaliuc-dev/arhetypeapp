def model_a(leading: str, creative: str) -> list[str]:
    """Модель А по двум первым функциям (правила позиционирования аспектов).

    1 = (A, v), 2 = (B, ¬v), 3 = (пара A, v), 4 = (пара B, ¬v),
    5 = (пара A, ¬v), 6 = (пара B, v), 7 = (A, ¬v), 8 = (B, v),
    где пары: N↔S, T↔F; v — вертность базовой функции.
    """
    a, v = leading[0], leading[1]
    b, v2 = creative[0], creative[1]
    if v2 != _FLIP[v]:
        raise ValueError("Базовая и творческая функции должны иметь разную вертность")
    if (a in "NS") == (b in "NS"):
        raise ValueError("Одна из функций Эго должна быть рациональной (T/F), другая — иррациональной (N/S)")
    nv = _FLIP[v]
    return [a + v, b + nv, _PAIR[a] + v, _PAIR[b] + nv, _PAIR[a] + nv, _PAIR[b] + v, a + nv, b + v]


def _jung_letters(leading: str, creative: str) -> str:
    """Соционическая четырёхбуквенная запись (последняя буква строчная: j/p)."""
    e = "E" if leading[1] == "e" else "I"
    ego = leading[0] + creative[0]
    n = "N" if "N" in ego else "S"
    t = "T" if "T" in ego else "F"
    p = "p" if leading[0] in "NS" else "j"
    return e + n + t + p


