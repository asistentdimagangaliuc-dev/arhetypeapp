def _build_tims() -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for en, ru, lead, crea, name, role in _TIM_ROWS:
        m = model_a(lead, crea)
        letters = _jung_letters(lead, crea)
        valued = {m[0], m[1], m[4], m[5]}
        quadra = next(k for k, q in QUADRAS.items() if q["values"] == valued)
        mbti_letters = letters.upper()
        if letters[0] == "I":  # у интровертов J/P в MBTI относится к первой ЭКСТРАВЕРТНОЙ функции
            mbti_functions = letters[:3].upper() + ("P" if letters[3] == "j" else "J")
        else:
            mbti_functions = mbti_letters
        out[en] = {
            "code_en": en, "code_ru": ru, "leading": lead, "creative": crea,
            "name_ru": name, "role_ru": role, "letters": letters, "model_a": m,
            "quadra": quadra, "quadra_ru": QUADRAS[quadra]["ru"],
            "club": CLUBS[letters[1] + letters[2]],
            "temperament": TEMPERAMENTS[letters[0] + letters[3]],
            "mbti_by_letters": mbti_letters, "mbti_by_functions": mbti_functions,
        }
    return out


