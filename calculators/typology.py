def _digit_root(n: int) -> int:
    while n > 9:
        n = sum(int(c) for c in str(n))
    return n


def _sign_range(b: Any, body: str) -> dict[str, Any]:
    """Знак тела (тропический). Без времени — проверка всех моментов календарной даты в поясах UTC−12…UTC+14."""
    from .common.ephemeris import SIGNS_RU, planet_positions, sign_of
    from .common.time import julian_day_ut, normalize

    if b.hour is not None and b.tz:
        nt = normalize(b)
        lon = planet_positions(nt.jd_ut)[body]["lon"]
        return {"sign": SIGNS_RU[sign_of(lon)], "sign_index": sign_of(lon), "lon": round(lon, 3), "ambiguous": False}
    start = datetime(b.year, b.month, b.day, tzinfo=timezone.utc) - timedelta(hours=14)
    end = datetime(b.year, b.month, b.day, tzinfo=timezone.utc) + timedelta(hours=36)
