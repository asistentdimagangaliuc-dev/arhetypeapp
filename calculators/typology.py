def _rank_types(adjusted: dict[int, int], anchors: dict[int, int]) -> list[int]:
    return sorted(adjusted, key=lambda t: (-adjusted[t], -anchors[t], t))


def score_enneagram(answers: dict[str, Any]) -> dict[str, Any]:
    """Подсчёт типа эннеаграммы, крыла, инстинктивной доминанты и тритипа.

    answers: {'EN-t-i': 0..4, 'IN-SP-i': 0..4, 'IN-FC-k': 'A'..'B', 'FU-avb': 'A'..'B'}.
    Ключи соционического блока игнорируются.
    """
    steps: list[str] = []
    warnings: list[str] = []
    flags: list[str] = []

    raw = {t: 0 for t in ENNEA_TYPES}
    anchors = {t: 0 for t in ENNEA_TYPES}
    answered = {t: 0 for t in ENNEA_TYPES}
    all_vals = []
    for iid, it in ENNEAGRAM_ITEMS.items():
        if iid in answers:
            v = _likert_value(iid, answers[iid])
            t = int(it.key)
            raw[t] += v
            answered[t] += 1
            all_vals.append(v)
            if it.anchor:
                anchors[t] = v
    missing = 36 - len(all_vals)
    if missing > 4:
        warnings.append(f"Не отвечено {missing} из 36 утверждений эннеаграммы — результат ненадёжен.")
    steps.append("Сырые баллы (сумма 4 утверждений, 0..16): " + ", ".join(f"{t}:{raw[t]}" for t in raw))

    fu = {t: 0 for t in ENNEA_TYPES}
    fu_used = []
    for iid, it in ENNEAGRAM_FOLLOWUP_ITEMS.items():
        if iid in answers:
            side, pts = _fc_value(iid, answers[iid])
            if side:
                t = int(it.pole_a if side == "a" else it.pole_b)
                fu[t] += pts
                fu_used.append(f"{iid}={answers[iid]} → +{pts} типу {t}")
    adjusted = {t: raw[t] + fu[t] for t in raw}
    if fu_used:
        steps.append("Уточняющие пункты: " + "; ".join(fu_used))
        steps.append("Скорректированные баллы: " + ", ".join(f"{t}:{adjusted[t]}" for t in adjusted))

    if all_vals:
        mean = sum(all_vals) / len(all_vals)
        if mean >= 3.2:
            flags.append(f"Средний ответ {mean:.2f} из 4 — почти всё «про меня» (социальная желательность или согласие со всем).")
        if max(raw.values()) - min(raw.values()) <= 3:
            flags.append("Плоский профиль: разница между максимальным и минимальным типом ≤ 3 балла.")

    ranking = _rank_types(adjusted, anchors)
    top, second = ranking[0], ranking[1]
    margin = adjusted[top] - adjusted[second]
    resolved_by = "score"
    core: int | None = top
    if margin == 0:
        if anchors[top] != anchors[second]:
            resolved_by = "anchor"
            steps.append(f"Ничья {top} и {second} ({adjusted[top]}): решает ключевой пункт EN-t-1 ({anchors[top]} > {anchors[second]}).")
        else:
            resolved_by = "unresolved"
            core = None
            steps.append(f"Ничья {top} и {second} ({adjusted[top]}), ключевые пункты тоже равны — тип не выдаётся.")
    steps.append("Ранжирование: " + " > ".join(f"{t}({adjusted[t]})" for t in ranking))

    # проверка ключевого утверждения ядра — ДО понижения уверенности (раздел 3.4, п. 4 и 9)
    if core is not None and anchors[core] <= 1 and answered[core] == 4:
        flags.append(f"Ключевое утверждение типа {core} (EN-{core}-1) оценено низко ({anchors[core]}) — проверьте тип интервью.")
    if resolved_by == "unresolved":
        level = "undetermined"
    elif resolved_by == "anchor" or margin <= 1:
        level = "low"
    elif margin >= 4 and raw[top] >= 11:
        level = "high"
    elif margin >= 2:
        level = "medium"
    else:
        level = "low"
    if flags and level in ("high", "medium"):
        level = "low" if level == "medium" else "medium"
        steps.append("Есть флаги согласованности — уверенность понижена на ступень.")

    # уточнения: соседние кандидаты в пределах 3 баллов
    followup_items, interview = [], []
    protocol_problem = any(f.startswith(("Плоский профиль", "Средний ответ")) for f in flags)
    close = [] if protocol_problem else [t for t in ranking[1:] if adjusted[ranking[0]] - adjusted[t] <= 3]
    for t in close:
        pair = frozenset({ranking[0], t})
        for iid, it in ENNEAGRAM_FOLLOWUP_ITEMS.items():
            if frozenset({int(it.pole_a), int(it.pole_b)}) == pair and iid not in answers:
                followup_items.append(iid)
        interview += ENNEAGRAM_INTERVIEW.get(pair, [])

    result: dict[str, Any] = {
        "method": "enneagram_questionnaire",
        "variant": "Ризо–Хадсон (Enneagram Institute): ядро, крыло, стрелы, центры; инстинкты — 3 вида; тритип — К. Фовр (вспомогательно)",
        "computable_from_birth_date": False,
        "scores": raw, "followup_points": fu, "adjusted": adjusted, "ranking": ranking,
        "confidence": {"level": level, "margin": margin, "top_raw": raw[top], "resolved_by": resolved_by},
    }
    if protocol_problem:
        result["recommendation"] = ("Профиль не дифференцирован: повторите опрос, попросив отвечать о типичном поведении "
                                    "с юности и использовать всю шкалу 0–4, либо проведите интервью о мотивах и страхах.")

    if core is None:
        # все типы, совпадающие с лидером и по баллу, и по ключевому пункту (при «4 на всё» — все девять)
        tied = [t for t in ranking if adjusted[t] == adjusted[top] and anchors[t] == anchors[top]]
        result.update({"type": None, "candidates": tied})
    else:
        w1, w2 = wings(core)
        dw = adjusted[w1] - adjusted[w2]
        if dw == 0:
            wing, wing_note = None, "крылья равны — крыло не выражено или оба"
        else:
            wing = w1 if dw > 0 else w2
            wing_note = "выраженное" if abs(dw) >= 2 else "слабое (разница 1 балл)"
        steps.append(f"Крыло: соседи {w1}({adjusted[w1]}) и {w2}({adjusted[w2]}) → {wing if wing else 'не определено'} ({wing_note}).")
        if wing and adjusted[core] - adjusted[wing] <= 1:
            flags.append(f"Крыло {wing} почти равно ядру {core} — проверьте, не является ли {wing} основным типом.")
        info = enneagram_type_info(core)
        result.update({
            "type": core, "wing": wing, "label": f"{core}w{wing}" if wing else str(core),
            "wing_detail": {"neighbors": {w1: adjusted[w1], w2: adjusted[w2]}, "note": wing_note},
            "name_ru": info["name_ru"], "name_en": info["name_en"],
            "core_fear": info["fear_ru"], "core_desire": info["desire_ru"],
            "passion": info["passion"], "virtue": info["virtue"],
            "arrows": {"integration": info["integration"], "disintegration": info["disintegration"]},
            "center": info["center"], "hornevian": info["hornevian"], "harmonic": info["harmonic"],
        })
        # тритип: лучший тип в каждом из двух других центров
        best = {}
        for c, members in CENTERS.items():
            r = sorted(members, key=lambda t: (-adjusted[t], -anchors[t], t))
            best[c] = r[0]
            if adjusted[r[0]] == adjusted[r[1]] and anchors[r[0]] == anchors[r[1]]:
                flags.append(f"Тритип: в центре {c} ничья между {r[0]} и {r[1]}.")
        core_c = info["center"]
        others = sorted([best[c] for c in CENTERS if c != core_c], key=lambda t: (-adjusted[t], t))
        result["tritype"] = f"{core}{others[0]}{others[1]}"
        steps.append(f"Тритип (ядро + лучший тип каждого другого центра): {result['tritype']}.")

    result["centers"] = {c: sum(adjusted[t] for t in m) for c, m in CENTERS.items()}

    # инстинкты
    inst = {k: 0 for k in INSTINCTS}
    inst_n = 0
    for iid, it in INSTINCT_ITEMS.items():
        if iid in answers:
            inst[it.key] += _likert_value(iid, answers[iid])
            inst_n += 1
    fc_detail = []
    for iid, it in INSTINCT_FC_ITEMS.items():
        if iid in answers:
            side, pts = _fc_value(iid, answers[iid])
            if side:
                k = it.pole_a if side == "a" else it.pole_b
                inst[k] += pts
                fc_detail.append(f"{iid}={answers[iid]} → +{pts} {k}")
    if inst_n or fc_detail:
        order = sorted(inst, key=lambda k: (-inst[k], list(INSTINCTS).index(k)))
        ties = [(order[i], order[i + 1]) for i in range(2) if inst[order[i]] == inst[order[i + 1]]]
        m1 = inst[order[0]] - inst[order[1]]
        ilevel = "undetermined" if m1 == 0 else ("low" if m1 <= 1 else ("medium" if m1 <= 3 else "high"))
        tie23 = inst[order[1]] == inst[order[2]]
        result["instincts"] = {
            "scores": inst, "order": order,
            "stacking": None if m1 == 0 else (f"{order[0]}/?" if tie23 else f"{order[0]}/{order[1]}"),
            "full_stacking": None if ties else "/".join(order),
            "dominant": order[0] if m1 else None, "blind_spot": None if tie23 else order[2],
            "confidence": ilevel, "ties": ties,
        }
        steps.append("Инстинкты: " + ", ".join(f"{k}:{inst[k]}" for k in inst)
                     + (" | " + "; ".join(fc_detail) if fc_detail else "")
                     + f" → {'/'.join(order)} (уверенность {ilevel})")
        if ties:
            flags.append(f"Инстинкты: равенство в паре(ах) {ties} — порядок условный, уточните вопросами интервью.")
        if inst_n < 12:
            warnings.append(f"Инстинкты: отвечено {inst_n} из 12 утверждений.")

    result["consistency_flags"] = flags
    result["warnings"] = warnings
    result["followup"] = {"items": list(dict.fromkeys(followup_items)), "interview": list(dict.fromkeys(interview))}
    result["steps"] = steps
    return result


def score_all(answers: dict[str, Any]) -> dict[str, Any]:
    """Оба блока сразу + список неизвестных ключей."""
    return {"socionics": score_socionics(answers), "enneagram": score_enneagram(answers),
            "unknown_keys": _unknown_keys(answers)}


