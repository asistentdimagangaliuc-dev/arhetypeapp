_LETTER_MAP = {"А": "A", "а": "a", "Б": "B", "б": "b", "0": "?", "": "?"}
_FC_POINTS = {"A": ("a", 2), "a": ("a", 1), "?": (None, 0), "b": ("b", 1), "B": ("b", 2)}


def _fc_value(item_id: str, raw: Any) -> tuple[str | None, int]:
    """Разобрать ответ на вопрос с вынужденным выбором -> ('a'|'b'|None, баллы 0..2)."""
    if not isinstance(raw, str):
        raise ValueError(f"{item_id}: ожидается 'A','a','?','b' или 'B', получено {raw!r}")
    v = _LETTER_MAP.get(raw.strip(), raw.strip())
    if v not in _FC_POINTS:
        raise ValueError(f"{item_id}: ожидается 'A','a','?','b' или 'B', получено {raw!r}")
    return _FC_POINTS[v]


def _likert_value(item_id: str, raw: Any) -> int:
    if isinstance(raw, bool) or not isinstance(raw, int) or not 0 <= raw <= 4:
        raise ValueError(f"{item_id}: ожидается целое 0..4, получено {raw!r}")
    return raw


