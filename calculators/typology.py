def intertype_relation(a: str, b: str) -> dict[str, Any]:
    """Отношение ТИМа a к ТИМу b (направленное для ревизии и заказа)."""
    ka, kb = resolve_tim(a), resolve_tim(b)
    ma = TIMS[ka]["model_a"]
    shape = (ma.index(TIMS[kb]["leading"]) + 1, ma.index(TIMS[kb]["creative"]) + 1)
    rel = _REL_BY_SHAPE[shape]
    info = RELATIONS[rel]
    return {
        "a": TIMS[ka]["code_ru"], "b": TIMS[kb]["code_ru"], "a_en": ka, "b_en": kb,
        "relation": rel, "name_ru": info["ru"], "name_en": info["en"],
        "symmetric": info["symmetric"],
        "shape": {"b_leading_in_a_model": shape[0], "b_creative_in_a_model": shape[1]},
        "explanation": (
            f"Базовая функция {TIMS[kb]['code_ru']} ({TIMS[kb]['leading']}) стоит у {TIMS[ka]['code_ru']} "
            f"на {shape[0]}-й позиции ({MODEL_A_FUNCTIONS[shape[0]]['ru']}), творческая "
            f"({TIMS[kb]['creative']}) — на {shape[1]}-й ({MODEL_A_FUNCTIONS[shape[1]]['ru']})."
        ),
    }


def partners(tim: str) -> dict[str, str]:
    """Все 16 направленных отношений для ТИМа: код отношения -> ТИМ партнёра (RU)."""
    k = resolve_tim(tim)
    return {intertype_relation(k, o)["relation"]: TIMS[o]["code_ru"] for o in TIM_ORDER}


def relation_table() -> dict[str, dict[str, str]]:
    """Полная таблица 16×16: строка a, столбец b -> код отношения a к b."""
    return {a: {b: intertype_relation(a, b)["relation"] for b in TIM_ORDER} for a in TIM_ORDER}


