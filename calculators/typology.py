def _confidence_level_soc(min_clarity: float, any_anchor: bool, any_unresolved: bool) -> str:
    if any_unresolved:
        return "undetermined"
    if any_anchor:
        return "low"
    if min_clarity >= 0.5:
        return "high"
    if min_clarity >= 0.25:
        return "medium"
    return "low"


def score_socionics(answers: dict[str, Any]) -> dict[str, Any]:
    """Подсчёт соционического ТИМа по ответам опросника.

    answers: {id пункта: 'A'|'a'|'?'|'b'|'B'} (кириллические А/а/Б/б тоже принимаются).
    Ключи других блоков игнорируются. Возвращает ТИМ, ясность каждой дихотомии,
    уровень уверенности, альтернативы, проверки согласованности и уточняющие вопросы.
    """
    steps: list[str] = []
    warnings: list[str] = []
    flags: list[str] = []
    dich: dict[str, dict[str, Any]] = {}
    per_item: dict[str, tuple[str | None, int]] = {}

    for iid, item in SOCIONICS_ITEMS.items():
        if iid in answers:
            per_item[iid] = _fc_value(iid, answers[iid])

    for scale, (pos, neg) in SOC_POLES.items():
        score, answered, strong = 0, 0, {pos: 0, neg: 0}
        detail = []
        for iid, item in SOCIONICS_ITEMS.items():
            if item.scale != scale or iid not in per_item:
                continue
            side, pts = per_item[iid]
            answered += 1
            pole = None if side is None else (item.pole_a if side == "a" else item.pole_b)
            if pole is not None:
                score += pts if pole == pos else -pts
                if pts == 2:
                    strong[pole] += 1
            detail.append(f"{iid}: {answers[iid]!s}→{pole or '0'}{'' if pole is None else ('+' if pole == pos else '-') + str(pts)}")
        maxp = 2 * answered
        clarity = abs(score) / maxp if maxp else 0.0
        resolved_by = "score"
        pole: str | None
        if score > 0:
            pole = pos
        elif score < 0:
            pole = neg
        else:
            anchor_id = f"SO-{scale}-1"
            pole = None
            if anchor_id in per_item and per_item[anchor_id][0] is not None:
                side = per_item[anchor_id][0]
                pole = SOCIONICS_ITEMS[anchor_id].pole_a if side == "a" else SOCIONICS_ITEMS[anchor_id].pole_b
                resolved_by = "anchor"
            else:
                resolved_by = "unresolved"
        if answered < 4:
            warnings.append(f"Шкала {scale}: отвечено {answered} пунктов (<4), результат ненадёжен.")
        if strong[pos] >= 2 and strong[neg] >= 2:
            flags.append(f"Шкала {scale}: сильные ответы в обе стороны ({strong[pos]} за {pos}, {strong[neg]} за {neg}) — противоречивый профиль.")
        a_id, b_id = SOCIONICS_CONTROL_PAIRS[scale]
        if a_id in per_item and b_id in per_item:
            sa, sb = per_item[a_id][0], per_item[b_id][0]
            if sa and sb:
                pa = SOCIONICS_ITEMS[a_id].pole_a if sa == "a" else SOCIONICS_ITEMS[a_id].pole_b
                pb = SOCIONICS_ITEMS[b_id].pole_a if sb == "a" else SOCIONICS_ITEMS[b_id].pole_b
                if pa != pb:
                    flags.append(f"Контрольная пара {a_id}/{b_id}: ответы указывают на разные полюса ({pa} и {pb}).")
        dich[scale] = {"pole": pole, "score": score, "max": maxp, "answered": answered,
                       "clarity": round(clarity, 3), "resolved_by": resolved_by}
        steps.append(f"{scale} ({SOC_SCALE_RU[scale]}): " + "; ".join(detail)
                     + f" | сумма {score:+d} из ±{maxp}, ясность {clarity:.2f} → {pole or '?'} ({resolved_by})")

    invalid_protocol = False
    all_answers = [v for k, v in per_item.items() if not SOCIONICS_ITEMS[k].extra]
    if all_answers:
        n_q = sum(1 for s, _ in all_answers if s is None)
        if n_q / len(all_answers) > 0.25:
            flags.append(f"Много ответов «?» ({n_q} из {len(all_answers)}) — пользователь не может выбирать, нужен разговор.")
        # «?» нейтрален: 23 ответа «A» и один «?» — такой же механический протокол, как 24 «A».
        decided = [s for s, _ in all_answers if s is not None]
        n_a = sum(1 for s in decided if s == "a")
        if len(decided) >= 12 and n_a in (0, len(decided)):
            invalid_protocol = True
            flags.append("Все ответы (кроме «?») на одной стороне (A или B) — признак механического ответа; "
                         "полюса в пунктах чередуются. Протокол недействителен.")
        elif len(decided) >= 12 and max(n_a, len(decided) - n_a) / len(decided) >= 0.8:
            # У последовательного респондента сторон A и B поровну (в каждой шкале 3 + 3), см. раздел 3.2.
            flags.append(f"Перекос ответов в одну сторону ({max(n_a, len(decided) - n_a)} из {len(decided)} на стороне "
                         f"{'A' if n_a * 2 > len(decided) else 'B'}) — возможна склонность соглашаться с первым/вторым вариантом.")

    if invalid_protocol:
        for d in dich.values():
            d["pole"], d["resolved_by"] = None, "invalid_protocol"
    unresolved = [s for s, d in dich.items() if d["pole"] is None]
    any_anchor = any(d["resolved_by"] == "anchor" for d in dich.values())
    min_clar = min(d["clarity"] for d in dich.values())
    level = _confidence_level_soc(min_clar, any_anchor, bool(unresolved))
    if flags and level == "high":
        level = "medium"
        steps.append("Есть флаги согласованности — уверенность понижена с high до medium.")

    def letters_for(poles: dict[str, str]) -> str:
        return poles["EI"] + poles["NS"] + poles["TF"] + ("j" if poles["JP"] == "J" else "p")

    result: dict[str, Any] = {
        "method": "socionics_questionnaire",
        "variant": "Модель А (А. Аугустинавичюте); 4 юнговские дихотомии по оригинальному опроснику",
        "computable_from_birth_date": False,
        "dichotomies": dich,
        "confidence": {"level": level, "min_clarity": round(min_clar, 3)},
        "consistency_flags": flags,
        "warnings": warnings,
    }

    followup_items: list[str] = []
    interview: list[str] = []
    for s, d in dich.items():
        if d["clarity"] < 0.5:
            # при недействительном протоколе уточняющие пункты бессмысленны: нужен повтор опроса или интервью
            if not invalid_protocol:
                for x in (f"SO-{s}-X1", f"SO-{s}-X2"):
                    if x not in answers:
                        followup_items.append(x)
            interview += SOCIONICS_INTERVIEW[s]

    if invalid_protocol:
        result.update({"tim": None, "candidates": [], "invalid_protocol": True})
        steps.append("Протокол недействителен (механические ответы): разрешение ничьих по ключевым пунктам отменено, "
                     "тип не выдаётся — нужен повторный опрос с разъяснением инструкции или интервью.")
    elif unresolved:
        candidates = []
        fixed = {s: d["pole"] for s, d in dich.items() if d["pole"]}
        for combo in itertools.product(*[SOC_POLES[s] for s in unresolved]):
            poles = dict(fixed)
            poles.update(dict(zip(unresolved, combo)))
            candidates.append(TIMS[tim_from_letters(letters_for(poles))]["code_ru"])
        result.update({"tim": None, "candidates": candidates})
        steps.append(f"Не определены дихотомии {unresolved}: кандидаты {candidates}. Тип не выдаётся.")
    else:
        poles = {s: d["pole"] for s, d in dich.items()}
        let = letters_for(poles)
        k = tim_from_letters(let)
        t = TIMS[k]
        steps.append(f"Буквы {let} → ТИМ {t['code_ru']} ({k}, «{t['name_ru']}»): "
                     f"{'иррационал — базовая функция воспринимающая' if let[3] == 'p' else 'рационал — базовая функция оценивающая'} "
                     f"{t['leading']}, творческая {t['creative']}.")
        alternatives = []
        for s, d in dich.items():
            if d["clarity"] < 0.34:
                alt_poles = dict(poles)
                alt_poles[s] = SOC_POLES[s][1] if poles[s] == SOC_POLES[s][0] else SOC_POLES[s][0]
                ak = tim_from_letters(letters_for(alt_poles))
                rel = intertype_relation(k, ak)
                alternatives.append({"tim": TIMS[ak]["code_ru"], "differs_in": s, "clarity": d["clarity"],
                                     "relation_to_main": rel["name_ru"]})
                pair = SOCIONICS_PAIR_INTERVIEW.get(frozenset({k, ak}))
                if pair:
                    interview += pair["questions"]
        result.update({
            "tim": t["code_ru"], "tim_en": k, "letters": let, "name_ru": t["name_ru"], "role_ru": t["role_ru"],
            "model_a": {str(i + 1): f"{a} — {MODEL_A_FUNCTIONS[i + 1]['ru']}" for i, a in enumerate(t["model_a"])},
            "quadra": t["quadra_ru"], "club": t["club"], "temperament": t["temperament"],
            "reinin": reinin_traits(k),
            "dual": partners(k)["duality"],
            "mbti_note": {
                "by_letters": t["mbti_by_letters"], "by_functions": t["mbti_by_functions"],
                "caveat": "Соционика и MBTI — разные системы; у интровертов J/P в MBTI указывает на первую экстравертную функцию, поэтому «по функциям» буква меняется. Совпадение типов по тестам разных систем частичное (по одному источнику около 30%).",
            },
            "alternatives": alternatives,
        })
    # уникализируем, сохраняя порядок
    result["followup"] = {"items": list(dict.fromkeys(followup_items)), "interview": list(dict.fromkeys(interview))}
    result["steps"] = steps
    return result


