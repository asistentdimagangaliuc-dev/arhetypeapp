def resolve_tim(code: str) -> str:
    """Привести обозначение ТИМа к английскому коду (ILE). Принимает ILE / ИЛЭ / ENTp / «Дон Кихот»."""
    c = code.strip()
    if c.upper() in TIMS:
        return c.upper()
    if c.upper() in _RU2EN:
        return _RU2EN[c.upper()]
    if len(c) == 4 and c[3] in "jp" and c[:3].upper() + c[3] in _LET2EN:
        return _LET2EN[c[:3].upper() + c[3]]
    if len(c) == 4 and c[3] in "JP" and c[:3].upper() + c[3].lower() in _LET2EN:
        raise ValueError(
            f"{code!r}: заглавная J/P неоднозначна (у интровертов MBTI и соционика расходятся). "
            "Укажите соционическую запись со строчной j/p (например, INTj) или код ТИМа (ЛИИ)."
        )
    for k, v in TIMS.items():
        if v["name_ru"].lower() == c.lower():
            return k
    raise ValueError(f"Неизвестный ТИМ: {code!r}")


def tim_from_letters(letters: str) -> str:
    """ТИМ (EN-код) по четырём дихотомиям, например 'ISTj' -> 'LSI'."""
    return resolve_tim(letters)


