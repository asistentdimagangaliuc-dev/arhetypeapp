def wings(t: int) -> tuple[int, int]:
    """Два соседних типа (возможные крылья): для 1 -> (9, 2), для 9 -> (8, 1)."""
    if t not in ENNEA_TYPES:
        raise ValueError("Тип эннеаграммы — целое от 1 до 9")
    return ((t - 2) % 9 + 1, t % 9 + 1)


def _group_of(t: int, groups: dict[str, tuple[int, ...]]) -> str:
    return next(k for k, v in groups.items() if t in v)


def enneagram_type_info(t: int) -> dict[str, Any]:
    """Справка по типу: крылья, стрелы, центр, группы Хорни и гармонические группы."""
    w = wings(t)
    return {
        "type": t, **ENNEA_TYPES[t], "wings": list(w),
        "integration": INTEGRATION[t], "disintegration": DISINTEGRATION[t],
        "center": _group_of(t, CENTERS), "hornevian": _group_of(t, HORNEVIAN),
        "harmonic": _group_of(t, HARMONIC),
    }


