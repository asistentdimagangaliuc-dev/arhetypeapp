def _parse_snapshot(lines):
    out = {}
    for ln in lines:
        day, rest = ln.split(":")
        out[day] = rest.split()
    return out


def test_liuren_ts_lib_720_table():
    ts = _parse_snapshot(TS_SNAPSHOT)
    ok_mzj = ok_depth = 0
    bad_mzj = []
    for d in range(60):
        day = ganzhi(d)
        for gs in range(12):
            off = (gs - JI_GONG[d % 10]) % 12
            exp = ts[day][gs]
            a = "".join(Z[x] for x in three_transmissions(d % 10, d % 12, off, 0)["chuan"])
            b = "".join(Z[x] for x in three_transmissions(d % 10, d % 12, off, 0, shehai="mengzhongji")["chuan"])
            ok_depth += a == exp
            ok_mzj += b == exp
            if b != exp:
                bad_mzj.append((day, Z[gs], exp))
    assert ok_mzj == 717 and ok_depth == 704
    # таблица не единообразна: 丁卯/辛卯 — по глубине 《大全》 (а 乙卯/己卯/癸卯 той же конфигурации — по 孟仲季);
    # 己亥 干上亥 «亥卯未» противоречит обоим правилам и опубликованному 《指南》 «癸未正月己亥日辛未时» (未亥卯)
    assert sorted(bad_mzj) == sorted([("丁卯", "巳", "亥酉未"), ("辛卯", "申", "亥酉未"), ("己亥", "亥", "亥卯未")])


