def di(gz: str) -> int:
    return next(i for i in range(60) if ganzhi(i) == gz)


def sc(day: str, hour: str, general: str, **kw) -> str:
    """Три передачи строкой по дню, ветви часа и месячному генералу."""
    d = di(day)
    r = three_transmissions(d % 10, d % 12, Z.index(general), Z.index(hour), **kw)
    return "".join(Z[x] for x in r["chuan"])


def kind(day: str, hour: str, general: str, **kw) -> list[str]:
    d = di(day)
    return three_transmissions(d % 10, d % 12, Z.index(general), Z.index(hour), **kw)["kind"]


