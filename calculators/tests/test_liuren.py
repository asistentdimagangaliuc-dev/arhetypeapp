def _all720(**kw):
    for d in range(60):
        for off in range(12):
            yield d, off, three_transmissions(d % 10, d % 12, off, 0, **kw)


def test_720_counts_daquan_juan1():
    cnt = Counter(r["method"] for _, _, r in _all720())
    assert sum(cnt.values()) == 720
    assert cnt["maoxing"] == 16      # «凡昴星止十六课» (卷一 «补论»)
    assert cnt["biezhe"] == 9        # «刚三柔六共九课» (卷一 «别责法»)
    assert cnt["fuyin"] == 60 and cnt["fanyin"] == 60
    assert cnt == Counter({"zeike": 337, "biyong": 81, "shehai": 76, "yaoke": 65, "fuyin": 60, "fanyin": 60,
                           "maoxing": 16, "bazhuan": 16, "biezhe": 9})


def test_720_biezhe_days():
    # «戊辰、戊午、丙辰三刚日各一课，辛未二课，辛丑二课，丁酉、辛酉各一课»;
    # «戊午戊辰与丙辰，干上皆午…辛丑辛未各二日，干上皆是丑未真。丁酉当为巳丁是，辛酉原来是酉辛»
    got = Counter(ganzhi(d) for d, _, r in _all720() if r["method"] == "biezhe")
    assert got == Counter({"戊辰": 1, "戊午": 1, "丙辰": 1, "辛未": 2, "辛丑": 2, "丁酉": 1, "辛酉": 1})
    gan_shang = {(ganzhi(d), Z[r["plate"][JI_GONG[d % 10]]]) for d, _, r in _all720() if r["method"] == "biezhe"}
    assert gan_shang == {("戊辰", "午"), ("戊午", "午"), ("丙辰", "午"), ("辛未", "丑"), ("辛未", "未"),
                         ("辛丑", "丑"), ("辛丑", "未"), ("丁酉", "巳"), ("辛酉", "酉")}


def test_720_bazhuan_only_on_five_days():
    # 《观月经》: «五日者，癸丑、甲寅、丁未、己未、庚申是也»; «盖八专日有五，除癸丑日俱有克»
    days = {ganzhi(d) for d, _, r in _all720() if r["method"] == "bazhuan"}
