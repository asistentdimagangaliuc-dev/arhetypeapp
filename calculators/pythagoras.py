def working_numbers(day: int, month: int, year: int, *, day_digit: str = "first_nonzero",
                    post2000_rule: str = "none", post2000_from_year: int = 2000) -> dict[str, Any]:
    """Рабочие числа + список дополнительных цифр варианта + шаги.

    Возвращает словарь: first, second, third, fourth, third_raw, multiplier_digit,
    extra_digits (что дописывается в квадрат сверх даты и рабочих чисел), post2000_applied, steps.
    """
    if post2000_rule not in POST2000_RULES:
        raise ValueError(f"post2000_rule должен быть одним из {POST2000_RULES}, получено {post2000_rule!r}")
    steps: list[str] = []
    dd = date_digits(day, month, year)
    extra: list[int] = []

    if post2000_rule == "sidorova":
        # Система «Идеал» Н. Сидоровой в пересказе tayniymir.com
        # (https://tayniymir.com/numerology/prognoz.html): «Сложите цифры: 1+1+1+9+8+4=24. Если дата
        # рождения до 2000 года, отнимаем 2, если позже, прибавляем 19. Это постоянное значение.
        # 24-2=22. Складываем: 2+2=4. Выписываем все цифры: 1.1.1984.24.2.22.4». На той же странице
        # пифагорейский ряд той же даты — «1.1.1984.24.6.22.4»: у Сидоровой на 2-м месте стоит
        # константа (2), а не сумма цифр 1-го числа, т. е. константа вписывается в ряд.
        # Правило задано для всех дат (−2 / +19), поэтому применяется при любом годе.
        first = sum(dd)
        const = 19 if year >= post2000_from_year else 2
        third_raw = first + 19 if const == 19 else first - 2
        third = abs(third_raw)
        fourth = digit_sum(third)
        nz = [x for x in dd if x]
        steps.append(f"Система «Идеал» (Н. Сидорова): 1-е число = сумма цифр даты: "
                     f"{' + '.join(str(x) for x in nz)} = {first}.")
        steps.append(f"Постоянное значение: {'+19 (рождение с ' + str(post2000_from_year) + ' г.)' if const == 19 else '−2 (рождение до ' + str(post2000_from_year) + ' г.)'}; "
                     f"оно вписывается в ряд вторым числом.")
        steps.append(f"3-е число: {first} {'+ 19' if const == 19 else '− 2'} = {third_raw}"
                     + (f" → по модулю {third}" if third_raw < 0 else "") + ".")
        steps.append(f"4-е число: сумма цифр {third} = {fourth} (один проход).")
        steps.append(f"Ряд: {day}.{month}.{year}.{first}.{const}.{third}.{fourth}")
        return {
            "first": first, "second": const, "third": third, "fourth": fourth,
            "third_raw": third_raw, "multiplier_digit": None,
            "extra_digits": [], "post2000_applied": True, "rule_applied": "sidorova",
            "steps": steps,
        }

    applied = post2000_rule != "none" and year >= post2000_from_year
    rule = post2000_rule if applied else "none"

    # 1-е число
    if rule == "year_1999":
        n_extra = year - 1999
        base = digits_of(day) + digits_of(month) + [1, 9, 9, 9] + digits_of(n_extra)
        first = sum(base)
        extra = [1, 9, 9, 9] + digits_of(n_extra)
        steps.append(
            f"Вариант «1999 + N» (Таяшева): {year} = 1999 + {n_extra}; "
            f"суммируем цифры дня, месяца, 1999 и {n_extra}: "
            f"{' + '.join(str(x) for x in base if x)} = {first} — 1-е число."
        )
    else:
        first = sum(dd)
        nz = [x for x in dd if x]
        steps.append(f"1-е число: сумма цифр даты {day:02d}.{month:02d}.{year:04d}: "
                     f"{' + '.join(str(x) for x in nz)} = {first}.")

    # 2-е число
    second = digit_sum(first)
    if first > 9:
        steps.append(f"2-е число: сумма цифр 1-го: {' + '.join(str(x) for x in digits_of(first))} = {second}"
                     + (" (двузначное — дальше НЕ сворачиваем)." if second > 9 else "."))
    else:
        steps.append(f"2-е число: 1-е однозначное, сумма его цифр = {second}.")

    # 3-е число
    mult = day_multiplier_digit(day, day_digit)
    if rule == "plus19":
        third_raw = first + 19
        steps.append(f"3-е число (вариант «+19» для рождённых с {post2000_from_year} г.): "
                     f"{first} + 19 = {third_raw}.")
    else:
        third_raw = first - 2 * mult
        how = ("первая ненулевая цифра дня" if day_digit == "first_nonzero"
               else "первая цифра записи дня (буквально)")
        steps.append(f"3-е число: 1-е − 2 × ({how} = {mult}): {first} − {2 * mult} = {third_raw}.")
    third = abs(third_raw)
    if third_raw < 0:
        steps.append(f"3-е число отрицательное ({third_raw}) — берём по модулю: {third}.")

    # 4-е число
    fourth = digit_sum(third)
    if third > 9:
        steps.append(f"4-е число: сумма цифр 3-го: {' + '.join(str(x) for x in digits_of(third))} = {fourth}"
                     + (" (двузначное — дальше НЕ сворачиваем)." if fourth > 9 else "."))
    else:
        steps.append(f"4-е число: 3-е однозначное, 4-е совпадает с ним: {fourth}.")

    if rule == "add_1_9":
        # Подтверждено кодом калькулятора web-calculator.ru
        # (https://web-calculator.ru/js/ezoterika/kvadrat-pifagora.js, 14.10.2026):
        # «a&&t>=2e3&&(l=l.concat([1,9]),o=!0)» — при включённом режиме и годе >= 2000 к списку цифр
        # (дата + классические рабочие числа) добавляется ровно одна 1 и одна 9 (флаг addedNineteen),
        # рабочие числа не меняются.
        extra = [1, 9]
        steps.append("Вариант «+1 и 9» (для рождённых с 2000 г.): в квадрат дополнительно вписываются "
                     "цифры 1 и 9 (по одной), рабочие числа классические (web-calculator.ru).")

    return {
        "first": first, "second": second, "third": third, "fourth": fourth,
        "third_raw": third_raw, "multiplier_digit": mult,
        "extra_digits": extra, "post2000_applied": applied, "rule_applied": rule,
        "steps": steps,
    }


def build_square(all_digits: list[int]) -> dict[int, int]:
    """Счётчики цифр 1–9 (нули отбрасываются)."""
    counts = {d: 0 for d in range(1, 10)}
    for x in all_digits:
        if x:
            counts[x] += 1
    return counts


def line_counts(counts: dict[int, int]) -> dict[str, int]:
    """Количество цифр в каждой из 8 линий."""
    return {k: sum(counts[d] for d in v["digits"]) for k, v in LINES.items()}


def calculate(b: BirthInput, *, post2000_rule: str = "none", day_digit: str = "first_nonzero",
              post2000_from_year: int = 2000, interpret: bool = True, **_: Any) -> dict[str, Any]:
    """Психоматрица (квадрат Пифагора) по дате рождения.

    Параметры:
        post2000_rule: ``none`` (по умолчанию — единый расчёт для любой даты),
            ``plus19`` (3-е = 1-е + 19, 2-е классическое, константа в квадрат не идёт — реконструкция),
            ``add_1_9`` (дописать в квадрат цифры 1 и 9), ``year_1999`` (год записывается как 1999 + N),
            ``sidorova`` (ряд системы «Идеал»: 1-е, константа 2 или 19, 1-е ∓ константа, сумма цифр).
            Варианты ``plus19``, ``add_1_9``, ``year_1999`` применяются только к датам с годом
            >= ``post2000_from_year``; ``sidorova`` — к любой дате (−2 до порога, +19 с порога).
        day_digit: ``first_nonzero`` (по умолчанию) или ``literal`` (для дня 05 удваивается 0).
        interpret: добавлять ли текстовые ключи интерпретации.
    Время и место рождения не используются.
    """
    date(b.year, b.month, b.day)  # проверка корректности даты (29.02 и т. п.)
    warnings: list[str] = []
    day, month, year = b.day, b.month, b.year

    wn = working_numbers(day, month, year, day_digit=day_digit,
                         post2000_rule=post2000_rule, post2000_from_year=post2000_from_year)
    steps = list(wn["steps"])

    dd = date_digits(day, month, year)
    nums = [wn["first"], wn["second"], wn["third"], wn["fourth"]]
    work_digits = [x for n in nums for x in digits_of(n)]
    all_digits = [x for x in dd if x] + list(wn["extra_digits"]) + [x for x in work_digits if x]
    counts = build_square(all_digits)
    lines = line_counts(counts)
    total = sum(counts.values())

    steps.append(
        "Цифры для квадрата (нули не учитываются): дата "
        f"{''.join(str(x) for x in dd if x)}"
        + (f" + доп. {''.join(str(x) for x in wn['extra_digits'])}" if wn["extra_digits"] else "")
        + f" + рабочие числа {wn['first']}, {wn['second']}, {wn['third']}, {wn['fourth']}"
        f" → всего {total} цифр."
    )
    steps.append("Раскладка: " + " / ".join(
        " | ".join((str(d) * counts[d]) or "—" for d in row) for row in GRID_LAYOUT))
    steps.append("Линии: " + ", ".join(f"{LINES[k]['name'].split(' (')[0]} {v}" for k, v in lines.items()))

    if wn["third_raw"] < 0:
        warnings.append(f"3-е число получилось отрицательным ({wn['third_raw']}); взят модуль "
                        f"{wn['third']} (Зорина 2017, Трошин, istashenko.com).")
    if day < 10 and day_digit == "first_nonzero" and wn["rule_applied"] != "sidorova":
        warnings.append("День однозначный: удваивается первая НЕНУЛЕВАЯ цифра дня (Александров пишет дату "
                        "без нулей). Вариант day_digit='literal' (удваивать 0) даёт другое 3-е число.")
    if wn["rule_applied"] == "sidorova":
        warnings.append("Ряд посчитан по системе «Идеал» Н. Сидоровой (−2 до 2000 г., +19 с 2000 г.; константа "
                        "вписана в ряд вместо 2-го числа). Это другая система: значения цифр у неё свои "
                        "(tayniymir.com), ключи интерпретации ниже относятся к классической психоматрице. "
                        "Опубликованного разбора даты после 2000 г. по этой системе не найдено.")
    elif year >= post2000_from_year:
        if wn["post2000_applied"]:
            warnings.append(f"Применён спорный вариант для рождённых после 2000 г.: {wn['rule_applied']} "
                            "(не канон; см. knowledge-base/08-pythagoras-square.md).")
        else:
            warnings.append("Дата после 2000 г.: посчитано по единому классическому правилу. Матрица обычно "
                            "содержит мало цифр и пустые ячейки — это ожидаемо; поправки (+19, «1 и 9», "
                            "1999+N) спорны, «сильные линии» — см. метод Александрова (док. 09).")
    elif post2000_rule != "none":
        warnings.append(f"Опция post2000_rule={post2000_rule!r} не применена: год {year} < {post2000_from_year}.")
    if year < 1918:
        warnings.append("Дата до 1918 г.: убедитесь, что она по григорианскому (новому) стилю — для России "
                        "до 14.02.1918 документы дают юлианскую дату; смена даже одной цифры меняет матрицу.")

    cells: dict[str, Any] = {}
    for d in range(1, 10):
        cell = {"count": counts[d], "digits": str(d) * counts[d], "name": CELL_NAMES[d],
                "scale": _general(counts[d])}
        if interpret:
            cell["key"] = _key(CELL_KEYS[d], counts[d])
        cells[str(d)] = cell

    lines_out: dict[str, Any] = {}
    for k, v in LINES.items():
        item = {"name": v["name"], "kind": v["kind"], "digits": list(v["digits"]), "count": lines[k],
                "scale": _general(lines[k])}
        if interpret:
            item["key"] = _key(LINE_KEYS[k], lines[k])
        lines_out[k] = item

    t, s = lines["temperament"], lines["spirituality"]
    if t == s:
        balance = "Духовная и материальная (плотская) составляющие уравновешены."
    elif t > s:
        balance = "Более склонен к материальной (плотской) стороне жизни."
    else:
        balance = "Более склонен к духовной стороне жизни."

    grid = [[str(d) * counts[d] for d in row] for row in GRID_LAYOUT]

    variant_parts = ["классический расчёт (Александров / популярная психоматрица)"]
    if day_digit != "first_nonzero":
        variant_parts.append("день: первая цифра буквально")
    if wn["post2000_applied"]:
        variant_parts.append(f"вариант после 2000: {wn['rule_applied']}")

    return {
        "method": METHOD,
        "variant": "; ".join(variant_parts),
        "inputs_used": {
            "date": f"{day:02d}.{month:02d}.{year:04d}",
            "day_digit": day_digit,
            "post2000_rule": post2000_rule,
            "post2000_from_year": post2000_from_year,
            "post2000_applied": wn["post2000_applied"],
            "time_used": False,
            "place_used": False,
        },
        "warnings": warnings,
        "date_digits": "".join(str(x) for x in dd),
        "working_numbers": {
            "first": wn["first"], "second": wn["second"], "third": wn["third"], "fourth": wn["fourth"],
            "third_raw": wn["third_raw"], "multiplier_digit": wn["multiplier_digit"],
        },
        "working_row": f"{wn['first']} {wn['second']} {wn['third']} {wn['fourth']}",
        "extra_digits": wn["extra_digits"],
        "all_digits": all_digits,
        "digits_total": total,
        "counts": {str(d): counts[d] for d in range(1, 10)},
        "cells": cells,
        "grid_layout": [list(r) for r in GRID_LAYOUT],
        "grid": grid,
        "lines": lines_out,
        "diagonal_balance": balance,
        # В ряду «Идеал» на 2-м месте стоит константа (2 или 19), а не «ведущее» число.
        "leading_number": None if wn["rule_applied"] == "sidorova" else wn["second"],
        "destiny_number": reduce_to_digit(wn["first"]),
        "notes": [
            "Ячейки: левый столбец 1-2-3, средний 4-5-6, правый 7-8-9 (строки 1-4-7, 2-5-8, 3-6-9).",
            "leading_number — 2-е число («ведущее» у Александрова); destiny_number — 1-е число, сведённое "
            "к одной цифре, только для справки: в квадрат НЕ вписывается.",
            "digits_total — «номер жизни» по Александрову (сколько цифр без нулей), трактовка эзотерическая.",
        ],
        "steps": steps,
    }
