def digits_of(n: int) -> list[int]:
    """Цифры числа (знак отбрасывается): 1999 -> [1, 9, 9, 9]."""
    return [int(c) for c in str(abs(int(n)))]


def digit_sum(n: int) -> int:
    """Сумма цифр за ОДИН проход: 29 -> 11, 39 -> 12 (дальше не сворачиваем)."""
    return sum(digits_of(n))


def reduce_to_digit(n: int) -> int:
    """Полное сведение к одной цифре 1–9 (0 остаётся 0): 29 -> 11 -> 2."""
    n = abs(int(n))
    while n > 9:
        n = digit_sum(n)
    return n


def date_digits(day: int, month: int, year: int) -> list[int]:
    """Все цифры даты в записи ДД.ММ.ГГГГ (с нулями)."""
    return [int(c) for c in f"{day:02d}{month:02d}{year:04d}"]


def day_multiplier_digit(day: int, rule: str = "first_nonzero") -> int:
    """Цифра дня, которую удваивают при расчёте 3-го числа.

    * ``first_nonzero`` (по умолчанию, Александров/Зорина/Трошин/web-calculator):
      05 -> 5, 15 -> 1, 30 -> 3;
    * ``literal`` (явно — zet.in.ua; так же выходит при буквальном чтении numerolog.ru и t-j.ru,
      хотя опубликованная numerolog.ru матрица 01.01.2015 совпадает с ``first_nonzero``):
      первая цифра записи ДД буквально, 05 -> 0.
    """
    if rule == "literal":
        return day // 10
    if rule == "first_nonzero":
        return day // 10 if day >= 10 else day
    raise ValueError(f"day_digit должен быть одним из {DAY_DIGIT_RULES}, получено {rule!r}")


def _key(table: list[CellKey], n: int) -> str:
    for lo, hi, text in table:
        if n >= lo and (hi is None or n <= hi):
            return text
    raise KeyError(n)  # pragma: no cover — таблицы полные


def _general(n: int) -> str:
    return GENERAL_SCALE[min(n, 6)]


