def digit_sum(n: int) -> int:
    """Однократная сумма цифр (19 → 10; однозначное число не меняется)."""
    return sum(int(c) for c in str(abs(n)))


def _digits(n: int) -> list[int]:
    return [int(c) for c in str(n)]


def gregorian_to_julian(y: int, m: int, d: int) -> tuple[int, int, int]:
    """Перевод григорианской даты в юлианскую (старый стиль) через номер юлианского дня."""
    a = (14 - m) // 12
    yy = y + 4800 - a
    mm = m + 12 * a - 3
    jdn = d + (153 * mm + 2) // 5 + 365 * yy + yy // 4 - yy // 100 + yy // 400 - 32045
    c = jdn + 32082
    dd = (4 * c + 3) // 1461
    e = c - (1461 * dd) // 4
    m5 = (5 * e + 2) // 153
    day = e - (153 * m5 + 2) // 5 + 1
    month = m5 + 3 - 12 * (m5 // 10)
    year = dd - 4800 + m5 // 10
    return year, month, day


def time_period(year: int) -> int:
    """Номер периода (1…5) метода временных интервалов = минимальное число цифр «сильной» линии."""
    return (year % 1000) // 200 + 1


def working_numbers(groups: list[int]) -> dict:
    """Четыре дополнительных числа по Александрову для записи даты из групп чисел.

    groups — числа записи без ведущих нулей в порядке «день месяц год»
    (допускается и запись из одного года, как в примерах автора: [1242], [988]).
    """
    record = " ".join(str(g) for g in groups)
    row = [int(c) for c in record.replace(" ", "")]
    first = sum(row)
    second = digit_sum(first)
    lead = row[0]  # первая цифра всего ряда (= первая значащая цифра дня)
    third_raw = first - 2 * lead
    third = abs(third_raw)  # «переставить числа местами»: 10 − 14 → 14 − 10
    fourth = digit_sum(third)
    return {
        "record": record,
        "row_digits": row,
        "lead_digit": lead,
        "first": first,
        "second": second,
        "third_raw": third_raw,
        "third": third,
        "fourth": fourth,
    }


def matrix_counts(row_digits: list[int], numbers: list[int]) -> tuple[dict[int, int], int]:
    """Счёт цифр 1–9 (ячейки психоматрицы) и отдельно нулей."""
    all_digits = list(row_digits)
    for n in numbers:
        all_digits.extend(_digits(n))
    counts = {d: all_digits.count(d) for d in range(1, 10)}
    return counts, all_digits.count(0)


