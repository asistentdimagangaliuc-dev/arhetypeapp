def psychomatrix_from_groups(groups: list[int], year: int | None = None) -> dict:
    """Полный расчёт по произвольной записи (используется и для дат-событий без дня/месяца)."""
    wn = working_numbers(groups)
    nums = [wn["first"], wn["second"], wn["third"], wn["fourth"]]
    counts, zeros = matrix_counts(wn["row_digits"], nums)
    lc = line_counts(counts)
    res = {
        "working_numbers": {"first": wn["first"], "second": wn["second"],
                            "third": wn["third"], "fourth": wn["fourth"]},
        "working_numbers_list": nums,
        "third_number_raw": wn["third_raw"],
        "counts": {str(d): counts[d] for d in range(1, 10)},
        "zeros": zeros,
        "lines": lc,
        "life_number": sum(counts.values()),
        "_wn": wn,
        "_counts": counts,
    }
    if year is not None:
        res["time_intervals"] = strong_lines_analysis(year, counts)
    return res


def calculate(b: BirthInput, **options) -> dict:
    """Психоматрица по Александрову.

    Опции:
      calendar = "gregorian" (по умолчанию) | "julian" — пересчитать введённую
        григорианскую дату в старый стиль (так автор считал даты России до 1918 г.);
      compare_generic = True — добавить сравнение с генерическим вариантом.
    """
    warnings: list[str] = []
    steps: list[str] = []
    calendar = str(options.get("calendar", "gregorian")).lower()
    y, m, d = b.year, b.month, b.day
    date(y, m, d)  # валидация даты
    if calendar == "julian":
        y, m, d = gregorian_to_julian(b.year, b.month, b.day)
        steps.append(f"Перевод в старый стиль: {b.day}.{b.month}.{b.year} (григ.) → {d}.{m}.{y} (юлиан.)")
        if (b.year, b.month, b.day) > (1918, 2, 13):
            warnings.append("Старый стиль применён к дате после 14.02.1918 — у Александрова так не делается.")
    elif calendar != "gregorian":
        raise ValueError("calendar должен быть 'gregorian' или 'julian'")

    groups = [d, m, y]
    pm = psychomatrix_from_groups(groups, year=y)
    wn, counts = pm["_wn"], pm["_counts"]
    first, second, third, fourth = pm["working_numbers_list"]

    steps.append(f"Запись даты без ведущих нулей: «{wn['record']}» (день месяц год)")
    steps.append("Числовой ряд: " + " ".join(map(str, wn["row_digits"])))
    steps.append("1) первое число = " + "+".join(map(str, wn["row_digits"])) + f" = {first}")
    steps.append(f"2) второе (ведущее) число = сумма цифр {first} = {second}")
    if wn["third_raw"] < 0:
        steps.append(f"3) третье число = {first} − 2×{wn['lead_digit']} = {wn['third_raw']} < 0 → "
                     f"по правилу автора переставляем: {2 * wn['lead_digit']} − {first} = {third}")
        warnings.append("Третье число получилось отрицательным; взят модуль (правило из «Тайн магических цифр»).")
    else:
        steps.append(f"3) третье число = {first} − 2×{wn['lead_digit']} (первая цифра ряда) = {third}")
    steps.append(f"4) четвёртое число = сумма цифр {third} = {fourth}")
    steps.append(f"Запись расчёта: {wn['record']} / {first} {second} {third} {fourth}")
    cells_str = {dd: (str(dd) * counts[dd]) or "—" for dd in range(1, 10)}
    steps.append("Психоматрица (строки 1-4-7 / 2-5-8 / 3-6-9): "
                 f"{cells_str[1]} {cells_str[4]} {cells_str[7]} / {cells_str[2]} {cells_str[5]} {cells_str[8]} / "
                 f"{cells_str[3]} {cells_str[6]} {cells_str[9]}; нулей: {pm['zeros']}")
    lc = pm["lines"]
    steps.append("Линии (количество цифр): " + ", ".join(f"{k}={v}" for k, v in lc.items()))
    ti = pm["time_intervals"]
    steps.append(f"Метод временных интервалов: {y} г. → {ti['period']}-й период; сильная линия — от "
                 f"{ti['threshold']} цифр; сильные: {', '.join(ti['strong_lines']) or 'нет'}")

    if y % 200 == 0:
        # Граница подтверждена автором: K1 (изд. 2011, thelib.ru, гл. 12) — «от 0 до 199 лет – достаточно одной
        # цифры…», «дата попадает в первый период (от 0 до 199 лет)» для 1 1 2000; TMC гл. 1 — «1-й период — от 0
        # до 199 года, от 1000 до 1199 года, от 2000 до 2199 года». Формулировка раннего издания DR «от 1 до 200
        # лет» — порядковые годы тысячелетия: тот же пример 1 1 2000 там отнесён к первому периоду.
        steps.append(f"Год {y} кратен 200 и открывает {pm['time_intervals']['period']}-й период (автор, K1 и TMC: "
                     "0–199, 200–399 …; «от 1 до 200 лет» раннего издания — те же годы в порядковом счёте).")
    if y >= 2000 and counts[9] == 0:
        warnings.append("Нет цифры 9: по автору для XXI в. девятку должны «создать» сильные линии "
                        "(см. time_intervals).")

    cells = {}
    for dd in range(1, 10):
        n = counts[dd]
        cells[str(dd)] = {
            "digits": str(dd) * n,
            "count": n,
            "meaning": CELL_NAMES[dd],
            "scale": scale_text(n),
            "reading": cell_reading(dd, n),
        }
    lines = {}
    for k, v in LINES.items():
        n = lc[k]
        lines[k] = {"cells": list(v["cells"]), "kind": v["kind"], "name": v["name"], "count": n,
                    "scale": scale_text(n), "reading": line_reading(k, n)}

    grid = [[cells_str[1], cells_str[4], cells_str[7]],
            [cells_str[2], cells_str[5], cells_str[8]],
            [cells_str[3], cells_str[6], cells_str[9]]]

    st = stability(counts)
    goal = {
        "future_and_goal": {"first": first, "second": second,
                            "note": "1-е число — качества, которые нужно развить для цели; 2-е (ведущее) — ведущее качество и цель"},
        "from_birth_parents": {"third": third, "fourth": fourth,
                               "note": "3-е и 4-е — качества, данные от рождения (во многом определены родителями)"},
        "present_digits_reversed": list(reversed(wn["row_digits"])),
        "author": "идея А. А. Рыбаковой, приведена у Александрова",
    }

    result: dict = {
        "method": METHOD,
        "variant": VARIANT,
        "inputs_used": {"date_gregorian": f"{b.year:04d}-{b.month:02d}-{b.day:02d}",
                        "calendar": calendar, "date_used": f"{d}.{m}.{y}",
                        "time_used": False, "place_used": False},
        "warnings": warnings,
        "date_record": wn["record"],
        "working_numbers": pm["working_numbers"],
        "working_numbers_list": pm["working_numbers_list"],
        "third_number_raw": wn["third_raw"],
        "lead_number": second,
        "counts": pm["counts"],
        "zeros": pm["zeros"],
        "grid": grid,
        "cells": cells,
        "lines": lines,
        "life_number": pm["life_number"],
        "time_intervals": ti,
        "stability": st,
        "goal_reading": goal,
        "possible_transitions": possible_transitions(counts),
        "calm_character": calm_character(counts[1], counts[8]),
        "steps": steps,
    }

    if options.get("compare_generic", True):
        # Сравнение ведётся по той же дате, что и основной расчёт (с учётом calendar=julian).
        g = _generic_numbers(y, m, d, "literal")
        doc08 = _generic_numbers(y, m, d, "first_nonzero")
        same = g == pm["working_numbers_list"]
        result["vs_generic"] = {
            "generic_variant": ("док. 08, day_digit='literal': ДД.ММ.ГГГГ с ведущими нулями; третье = |первое − "
                                "2×первая цифра записи| (0 для дней 1–9; zet.in.ua)"),
            "generic_numbers": g,
            "same_numbers": same,
            "doc08_default_numbers": doc08,
            "same_as_doc08_default": doc08 == pm["working_numbers_list"],
            "note": ("совпадает" if same else
                     "расходится с вариантом «буквальный 0»: у Александрова удваивается первая значащая цифра "
                     "дня; с вариантом док. 08 по умолчанию числа совпадают"),
        }
    return result


def compatibility(husband: BirthInput, wife: BirthInput, **options) -> dict:
    """Совместимость супругов по Александрову: сравнение линий (гл. 6–10) и срок
    стабильности брака (гл. 13). Возвращает числа и флаги, а не «вердикт»."""
    h = calculate(husband, **options)
    w = calculate(wife, **options)
    hl = {k: v["count"] for k, v in h["lines"].items()}
    wl = {k: v["count"] for k, v in w["lines"].items()}
    flags: list[str] = []
    # Первая строка: лидирует более целеустремлённый.
    if hl["row_147"] > wl["row_147"]:
        flags.append("Целеустремлённость (1-4-7) сильнее у мужа — лидерство по целям за ним.")
    elif hl["row_147"] < wl["row_147"]:
        flags.append("Целеустремлённость (1-4-7) сильнее у жены — лидерство по целям за ней.")
    else:
        flags.append("Целеустремлённость (1-4-7) равна — лидера определять по характеру (цифра 1).")
    # Вторая строка.
    if hl["row_258"] >= 4 and wl["row_258"] >= 4:
        flags.append("Оба сильные семьяне (2-5-8 ≥ 4).")
    elif hl["row_258"] <= 3 and wl["row_258"] <= 3:
        flags.append("У обоих слабое качество семьянина (2-5-8 ≤ 3) — не испытывать семью раздельным отдыхом.")
    # Третья строка: разница не более 2.
    if abs(hl["row_369"] - wl["row_369"]) > 2:
        flags.append("Стабильность (3-6-9) различается более чем на 2 цифры — риск «домосед vs революционер».")
    # Второй столбец: сильнее у мужа — крепче семья.
    if wl["col_456"] > hl["col_456"]:
        flags.append("Линия обеспечения семьи (4-5-6) сильнее у жены — автор считает это фактором риска.")
    # Плотская диагональ: разница не более 1, желательно сильнее у мужа.
    if abs(hl["diag_357"] - wl["diag_357"]) > 1:
        flags.append("Темперамент (3-5-7) различается более чем на 1 цифру.")
    # Соотношение диагоналей.
    hr = (hl["diag_357"], hl["diag_159"])
    wr = (wl["diag_357"], wl["diag_159"])
    if (hr[0] - hr[1]) * (wr[0] - wr[1]) < 0:
        flags.append("У одного преобладает плотская диагональ, у другого — духовная: автор считает это несовместимостью.")
    sy = stability_years(h["stability"]["bytovaya"], w["stability"]["bytovaya"],
                         h["stability"]["dukhovnaya"], w["stability"]["dukhovnaya"])
    return {
        "method": METHOD + "_compatibility",
        "variant": VARIANT,
        "inputs_used": {"husband": h["inputs_used"], "wife": w["inputs_used"]},
        "warnings": h["warnings"] + w["warnings"],
        "husband": {"record": h["date_record"], "numbers": h["working_numbers_list"], "lines": hl,
                    "stability": h["stability"]},
        "wife": {"record": w["date_record"], "numbers": w["working_numbers_list"], "lines": wl,
                 "stability": w["stability"]},
        "marriage_stability": sy,
        "flags": flags,
        "steps": [
            f"БСм = {h['stability']['bytovaya']}, БСж = {w['stability']['bytovaya']}, "
            f"ДСм = {h['stability']['dukhovnaya']}, ДСж = {w['stability']['dukhovnaya']}",
            f"БСС = {sy['BSS']} → {sy['BSS']}/365 ≈ {sy['bss_years']} лет (период бытового кризиса)",
            f"ДСС = {sy['DSS']} → {sy['DSS']}/365 ≈ {sy['dss_years']} лет (период духовного кризиса)",
            f"ОСС = {sy['bss_years']} + {sy['dss_years']} = {sy['OSS_years']} лет",
        ],
    }


