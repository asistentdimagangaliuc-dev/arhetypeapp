def strong_lines_analysis(year: int, counts: dict[int, int]) -> dict:
    """Метод временных интервалов: какие линии «сильные» и сколько дополнительных цифр
    максимум может получить каждая ячейка (каждая сильная линия порождает ОДНУ цифру
    в одной из своих ячеек; созданные цифры в матрицу не вписываются — это потенциал)."""
    period = time_period(year)
    lc = line_counts(counts)
    strong = [k for k, n in lc.items() if n >= period]
    per_cell = {d: sum(1 for k in strong if d in LINES[k]["cells"]) for d in range(1, 10)}
    lo, hi = PERIOD_TABLE[period]
    return {
        "period": period,
        "period_years_in_millennium": f"{lo}–{hi}",
        "threshold": period,
        "strong_lines": strong,
        "max_extra_total": len(strong),
        "max_extra_per_cell": {str(d): per_cell[d] for d in range(1, 10)},
    }


def stability(counts: dict[int, int]) -> dict:
    """Бытовая (БС = А×Б×В) и духовная (ДС = Г×Д×Е) стабильность (Кн. 1, гл. 13).

    А — плотская диагональ 3-5-7, Б — строка 3-6-9, В — строка 2-5-8;
    Г — духовная диагональ 1-5-9, Д — столбец 1-2-3, Е — строка 1-4-7.
    """
    lc = line_counts(counts)
    a, b, v = lc["diag_357"], lc["row_369"], lc["row_258"]
    g, d, e = lc["diag_159"], lc["col_123"], lc["row_147"]
    return {
        "bytovaya": a * b * v,
        "dukhovnaya": g * d * e,
        "factors": {"A_357": a, "B_369": b, "V_258": v, "G_159": g, "D_123": d, "E_147": e},
    }


def stability_years(bs_husband: int, bs_wife: int, ds_husband: int, ds_wife: int) -> dict:
    """Срок стабильности брака (Кн. 1, гл. 13): БСС = БСм×БСж, ДСС = ДСм×ДСж,
    периоды кризисов = БСС/365 и ДСС/365 (округление до целых), ОСС = сумма округлённых лет."""
    bss = bs_husband * bs_wife
    dss = ds_husband * ds_wife
    bss_years_raw = bss / 365
    dss_years_raw = dss / 365
    bss_years = round(bss_years_raw)
    dss_years = round(dss_years_raw)
    oss = bss_years + dss_years
    critical = False
    reasons = []
    if bss_years and dss_years:
        if bss_years == dss_years:
            critical = True
            reasons.append("периоды кризисов по быту и по духовности совпадают")
        elif max(bss_years, dss_years) % min(bss_years, dss_years) == 0:
            critical = True
            reasons.append("периоды кризисов кратны друг другу")
    if oss < 50:
        reasons.append("общая стабильность меньше 50–60 лет (автор считает брак стабильным при ≥50–60)")
    return {
        "BSS": bss, "DSS": dss,
        "bss_years": bss_years, "dss_years": dss_years,
        "bss_years_raw": round(bss_years_raw, 2), "dss_years_raw": round(dss_years_raw, 2),
        "OSS_years": oss,
        "critical": critical or bss_years == 0 or dss_years == 0,
        "notes": reasons,
    }


def possible_transitions(counts: dict[int, int]) -> list[dict]:
    """Структурно возможные «переходы цифр» (зависят от поведения человека, а не от даты)."""
    out: list[dict] = []
    c = counts
    if c[1] >= 2:
        out.append({"transition": "11 → 8", "effect": "терпимость: −11, +8, награда +22 или +4; сопровождается 6 → 7",
                    "direction": "положительный"})
    if c[8] >= 1:
        out.append({"transition": "8 → 11", "effect": "власть: −8, +11, потеря 22 или 4; сопровождается 7 → 6",
                    "direction": "отрицательный"})
    if c[4] >= 1:
        out.append({"transition": "4 → 22", "effect": "энергия за счёт здоровья (при дефиците 2)", "direction": "нейтральный"})
    if c[2] >= 2:
        out.append({"transition": "22 → 4", "effect": "здоровье за счёт энергии", "direction": "нейтральный"})
    if c[6] >= 1:
        out.append({"transition": "6 → 7", "effect": "искусство, чтение, терпимость, доброта", "direction": "положительный"})
    if c[7] >= 1:
        out.append({"transition": "7 → 6", "effect": "потеря долга к родителям/терпимости, агрессия", "direction": "отрицательный"})
    # Переход 5 ↔ 9 у автора двусторонний ([DR], «Цифра 5…»: «55 дают 9 и 99 дают 5»;
    # «Переходы цифр»: «55 — дополнительно 9», «если 99, то можно дополнить одной цифрой 5»).
    if c[5] >= 2:
        out.append({"transition": "55 → +9", "effect": "сильная логика восстанавливает события по цепочке — дополнительная цифра памяти",
                    "direction": "положительный"})
    if c[9] >= 2:
        out.append({"transition": "99 → +5", "effect": "память «сличением» дополняет одну цифру логики", "direction": "положительный"})
    return out


def calm_character(n1: int, n8: int) -> str | None:
    """Характер «в спокойном состоянии» (Кн. 1, гл. 16–17; раннее изд., «Чувство долга 8-нет»):
    при 3–5 единицах каждая пара единиц (кроме последней) даёт восьмёрку: 111→1 и 8,
    1111→11 и 8, 11111→1 и 88."""
    if 3 <= n1 <= 5:
        pairs = (n1 - 1) // 2
        rest = n1 - 2 * pairs
        return f"{'1' * rest} и {'8' * (n8 + pairs)}"
    return None


def _generic_numbers(y: int, m: int, d: int, day_digit: str = "literal") -> list[int]:
    """Четыре числа по калькулятору документа 08 (``calculators/pythagoras.py``).

    * ``day_digit="literal"`` — запись ДД.ММ.ГГГГ с ведущими нулями и удвоение первой цифры
      записи буквально (для дней 1–9 это 0): явно так у zet.in.ua, так же получается при
      буквальном чтении t-j.ru и numerolog.ru;
    * ``day_digit="first_nonzero"`` — вариант документа 08 по умолчанию; его числа всегда
      совпадают с числами Александрова (та же цифра дня, тот же модуль).
    """
    from .pythagoras import working_numbers as _pyth_wn  # локальный импорт: модули независимы

    w = _pyth_wn(d, m, y, day_digit=day_digit)
    return [w["first"], w["second"], w["third"], w["fourth"]]


